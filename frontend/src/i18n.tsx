function resolveLocale(language?: string | null): Locale {
  if (language?.startsWith('en')) {
    return 'en-US';
  }
  if (language?.startsWith('es')) {
    return 'es-ES';
  }
  return 'pt-BR';
}

function getTranslation(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const value = translations[locale][key] ?? translations['pt-BR'][key] ?? key;
  if (!params) {
    return value;
  }

  return Object.entries(params).reduce((acc, [paramKey, paramValue]) => {
    return acc.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
  }, value);
}

function getNavigatorLocale(): Locale {
  if (typeof navigator === 'undefined') {
    return 'pt-BR';
  }
  const browserLanguage = navigator.language || navigator.languages?.[0];
  return resolveLocale(browserLanguage);
}

export function LanguageProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [locale, setLocaleState] = useState<Locale>(() => getNavigatorLocale());

  useEffect(() => {
    const savedLocale = window.localStorage.getItem('app-locale');
    if (savedLocale === 'en-US' || savedLocale === 'pt-BR' || savedLocale === 'es-ES') {
      setLocaleState(savedLocale);
    }
  }, []);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem('app-locale', nextLocale);
  };

  const t = (key: string, params?: Record<string, string | number>) => getTranslation(locale, key, params);

  const value = useMemo<TranslationContextValue>(() => ({ locale, setLocale, t }), [locale]);

  useEffect(() => {
    document.documentElement.lang =
      locale === 'en-US' ? 'en' : locale === 'es-ES' ? 'es' : 'pt';
  }, [locale]);

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useTranslation(): TranslationContextValue {
  const context = useContext(TranslationContext);
  if (!context) {
    throw new Error('useTranslation must be used inside a LanguageProvider');
  }
  return context;
}
